let language = FALLBACK;
const listeners = new Set();

/** Maps a Host or browser locale tag onto a supported language. */
export function resolveLanguage(tag, preference = 'auto') {
  if (preference === 'zh-Hans' || preference === 'en') return preference;
  const value = typeof tag === 'string' ? tag.toLowerCase() : '';
  return value.startsWith('en') ? 'en' : FALLBACK;
}

export function getLanguage() {
  return language;
}

export function setLanguage(tag, preference = 'auto') {
  const next = resolveLanguage(tag, preference);
  if (next === language) return language;
  language = next;
  for (const listener of [...listeners]) {
    try { listener(language); } catch { /* A view listener must not break the others. */ }
  }
  return language;
}

export function onLanguageChange(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** Interpolates `{{name}}` placeholders; missing values stay visible as the placeholder. */
export function translate(key, params, tag = language) {
  const table = MESSAGES[tag] ?? MESSAGES[FALLBACK];
  const template = table[key] ?? MESSAGES[FALLBACK][key] ?? key;
  if (!params) return template;
  return template.replace(/\{\{(\w+)\}\}/gu, (match, name) => (
    Object.hasOwn(params, name) ? String(params[name]) : match
  ));
}

export const t = translate;

/** BCP 47 tag for dates and numbers. */
export function localeFor(tag = language) {
  return tag === 'en' ? 'en-US' : 'zh-CN';
}
