/**
 * Nothing in the stylesheet is dead.
 *
 * Two properties, one shape: a declaration earns its place by being read.
 *
 *   1. Every class selector has at least one consumer outside `<style>`.
 *   2. Every custom property declared is read at least once by `var()`.
 *
 * Written as properties rather than as a list of names. The list this replaced — eleven class
 * names found by hand — would only stop the next person from re-adding those eleven, and a dead
 * rule nobody checks is a dead rule that comes back two refactors later.
 *
 * What this caught, and why a scanner had to be calibrated rather than trusted:
 *
 *   - `.legend` was dead and the hand sweep missed it, twice. Both passes read it as live
 *     because it sits in the middle of a block of live rules.
 *   - The ten `pill-*` classes are generated by `'pill' + (tone ? ' pill-' + tone : '')`. Note
 *     the leading space: a producer pattern anchored to the quote character reads that as no
 *     producer at all and reports all ten as dead. Every earlier version of this scanner did.
 *   - `.is-reading-down` exists only inside a comment, which describes a rule that was
 *     deliberately deleted while a guard keeps asserting the comment survived. Counting
 *     comments as consumers is what makes that class look alive, so comments are stripped
 *     before anything is counted.
 *   - The word "chips" appears in English prose in a dozen comments. `chip` must not match
 *     inside `chips` or `chip-mark`, so consumers are matched on token boundaries that reject
 *     both.
 *
 * The failure this guard is calibrated against is a false positive, not a miss: a guard that
 * blocks legitimate work gets argued with, and the next version of it gets weakened. That is
 * why a generated class counts as consumed only when the generator can name its suffix — see
 * `consumedBy`. The looser rule that exempted every class under a prefix was tried first and
 * had to go: it passed a mutation that deleted the only consumer of `.turn-meta`.
 */
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const HTML = fileURLToPath(new URL('../miniapp/client/index.html', import.meta.url));
const html = readFileSync(HTML, 'utf8');

let pass = 0;
const failures = [];
function assert(name, cond, detail) {
  if (cond) pass += 1;
  else failures.push(detail ? `${name}\n      ${detail}` : name);
}

/* The block is located by its own delimiters. Slicing on an assumed order of <style> and
 * <script> is how an earlier scan cut the whole body away and reported 163 dead of 83 live. */
const styleStart = html.indexOf('<style');
const styleEnd = html.lastIndexOf('</style>');
assert('the page has exactly one <style> block', styleStart >= 0 && styleEnd > styleStart);
if (styleStart < 0 || styleEnd <= styleStart) {
  console.log('css: ' + pass + ' passed, ' + failures.length + ' failed');
  for (const f of failures) console.log('FAIL  ' + f);
  process.exit(1);
}
const css = html.slice(html.indexOf('>', styleStart) + 1, styleEnd);
let outside = html.slice(0, styleStart) + html.slice(styleEnd);

/* Comments first, everywhere: a comment is prose about the code, not the code. */
const strip = (s) => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/<!--[\s\S]*?-->/g, ' ');
const cssLive = strip(css);
outside = strip(outside).replace(/^\s*\/\/.*$/gm, ' ');

assert('the stylesheet is not empty after comments are stripped', cssLive.trim().length > 0);

/* ------------------------------------------------------------------ class selectors */
/* A dot must be followed by an identifier start, which keeps `0.86` and `1.5rem` out;
 * `url(...)` contents are dropped first for the same reason. */
const selectors = new Map();
for (const m of cssLive.replace(/url\([^)]*\)/g, ' ').matchAll(/\.(-?[_a-zA-Z][\w-]*)/g)) {
  selectors.set(m[1], (selectors.get(m[1]) || 0) + 1);
}

const escRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

/* A class assembled by concatenation has no literal to match, so the generator behind it has
 * to be found instead. The space after the quote and the space before the `+` are both
 * load-bearing; both were missing at some point and both report all ten pill classes as dead. */
const prefixes = new Set();
for (const m of outside.matchAll(/'([ \t]*[\w-]*-)'|"([ \t]*[\w-]*-)"/g)) {
  if (/^\s*\+/.test(outside.slice(m.index + m[0].length))) prefixes.add((m[1] || m[2]).trim());
}

const consumedBy = (name) => {
  if (new RegExp('(?<![-\\w])' + escRe(name) + '(?![\\w-])').test(outside)) return 'a literal';
  for (const p of prefixes) {
    if (!p || !name.startsWith(p)) continue;
    // A loose prefix rule would be simpler and is wrong in a way that cannot be seen: it
    // marks *every* class under the prefix consumed forever, so deleting the only consumer of
    // `.turn-meta` leaves the rule looking alive and the guard green. A mutation that did
    // exactly that survived the first version of this file.
    //
    // So a prefix only covers a class it can *name*. The generator draws its values from a
    // fixed list of string literals — `' pill-' + tone` where `kindTone()` returns one of nine
    // — so `pill-user` is alive because `'user'` appears as a literal, and that is checkable
    // without following the data. A prefix that cannot name the suffix covers nothing.
    if (new RegExp("'\\s*" + escRe(name.slice(p.length)) + "'").test(outside)) return `'${p}' + …`;
  }
  return '';
};

const deadClasses = [...selectors.keys()].filter((name) => !consumedBy(name));
assert('every class selector in the stylesheet has a consumer outside it',
  deadClasses.length === 0,
  'no consumer: ' + deadClasses.map((n) => '.' + n).join(', '));

/* A generated family is only as alive as its producer. Asserting the producer still exists
 * keeps a guard that has quietly stopped matching the generator from also being the reason the
 * ten classes look dead — a failure that would read as "delete them". The tolerance for a
 * leading space is the same one the extraction needs: the literal is `' pill-'`. */
for (const p of prefixes) {
  if (!p || p === '-') continue;
  assert(`the generated family '${p}' is still produced by a concatenation`,
    new RegExp("'\\s*" + escRe(p) + "'|\"\\s*" + escRe(p) + "\"").test(outside));
}

/* ---------------------------------------------------------------- custom properties */
/* The other half of the same property, and it is not hypothetical: deleting `.btn-primary`
 * orphaned `--mcode-primary-action-bg` and `--mcode-primary-action-text` in all three theme
 * blocks — six declarations that would have sat there looking like part of the design. */
const declared = new Set();
for (const m of cssLive.matchAll(/(--[\w-]+)\s*:/g)) declared.add(m[1]);
for (const name of declared) {
  const uses = cssLive.split('var(' + name + ')').length - 1;
  assert(`${name} is read somewhere`, uses > 0, 'declared but never passed to var()');
}

/* The reverse check has one exception and it is a whole family, not an allowance: nineteen
 * properties — every `--ov-*`, `--sticky-*` and `--inspector-*` — are never declared in the
 * stylesheet at all. `renderOverview()` writes them per span with `setProperty`, and the
 * stylesheet reads them back with `var()`. Asserting "read but never declared" without knowing
 * that would fail on all nineteen and would be wrong every time. So a read with no declaration
 * is only a defect when nothing sets it either. */
const setFromJs = new Set();
for (const m of outside.matchAll(/setProperty\(\s*['"](--[\w-]+)/g)) setFromJs.add(m[1]);
const read = new Set();
for (const m of cssLive.matchAll(/var\(\s*(--[\w-]+)/g)) read.add(m[1]);
for (const name of read) {
  if (declared.has(name) || setFromJs.has(name)) continue;
  assert(`${name} is declared somewhere`, false, 'read by var(), never declared, never set from JS');
}

/* And the other direction for the JS-written ones: a `setProperty` whose name nothing reads is
 * the same orphan as a dead rule, just spelled differently. */
for (const name of setFromJs) {
  assert(`${name} written from JS is read by the stylesheet`,
    new RegExp('var\\(\\s*' + escRe(name) + '\\b').test(cssLive));
}

console.log('css: ' + pass + ' passed, ' + failures.length + ' failed'
  + ' (' + selectors.size + ' class selectors, ' + declared.size + ' custom properties)');
if (failures.length) {
  for (const f of failures) console.log('FAIL  ' + f);
  process.exit(1);
}
console.log('ALL CHECKS PASSED');
