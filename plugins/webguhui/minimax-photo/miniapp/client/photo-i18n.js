export const languages = [
  ['auto', '跟随浏览器'],
  ['zh-hans', '简体中文'],
  ['zh-hant', '繁體中文'],
  ['en', 'English'],
  ['ja', '日本語'],
];
export function resolveLanguage(choice, browserLanguages = []) {
  if (choice !== 'auto' && languages.some(([code]) => code === choice)) return choice;
  for (const tag of browserLanguages) {
    const code = tag.toLowerCase();
    if (code.startsWith('zh'))
      return code.includes('hans') ? 'zh-hans' : /hant|tw|hk|mo/.test(code) ? 'zh-hant' : 'zh-hans';
    if (code.startsWith('ja')) return 'ja';
    if (code.startsWith('en')) return 'en';
  }
  return 'en';
}
let preference = 'auto',
  locale = 'zh-hans';
const listeners = new Set();
export const subscribeLanguage = (fn) => {
  listeners.add(fn);
  return () => listeners.delete(fn);
};
export const getLanguage = () => locale;
export const getPreference = () => preference;
export function setLanguage(choice, persist = true) {
  preference = languages.some(([code]) => code === choice) ? choice : 'auto';
  locale = resolveLanguage(preference, navigator.languages || [navigator.language]);
  document.documentElement.lang = { 'zh-hans': 'zh-CN', 'zh-hant': 'zh-TW', en: 'en', ja: 'ja' }[
    locale
  ];
  if (persist)
    try {
      localStorage.setItem('minimax-photo.language', preference);
    } catch {}
  for (const fn of listeners) fn();
}
export function initLanguage() {
  let saved = 'auto';
  try {
    saved = localStorage.getItem('minimax-photo.language') || 'auto';
  } catch {}
  setLanguage(saved, false);
}
