// Precompile the Atlas JSX sources in src/ into plain browser scripts in miniapp/client/build/.
// Usage: npm run build   (needs esbuild, installed by `npm install`; node_modules is not committed)
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { transform } from 'esbuild';

const root = join(import.meta.dirname, '..');
const out = join(root, 'miniapp', 'client', 'build');
const files = ['renderers', 'ui-helpers', 'views', 'search-overlay', 'app'];
await mkdir(out, { recursive: true });
for (const name of files) {
  const source = await readFile(join(root, 'src', `${name}.jsx`), 'utf8');
  const { code } = await transform(source, {
    loader: 'jsx', jsx: 'transform', format: 'iife', target: 'es2020', legalComments: 'inline',
    banner: `// Generated by scripts/build.mjs from src/${name}.jsx. Do not edit.`,
  });
  await writeFile(join(out, `${name}.js`), code);
}
process.stderr.write(`built ${files.length} files into miniapp/client/build\n`);
